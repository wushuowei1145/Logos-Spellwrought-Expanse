def entries(base, talk):
    out = dict(base)
    for k, v in talk.items():
        out[L + 'talk.' + k] = v
    return out


def add(path, kv):
    raw = path.read_bytes().decode('utf-8')
    have = json.loads(raw)
    new = {k: v for k, v in kv.items() if k not in have}
    if not new:
        print(path.name, '没有新键')
        return
    body = raw.rstrip()
    assert body.endswith('}')
    body = body[:-1].rstrip()
    lines = ',\n'.join(f'  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}' for k, v in new.items())
    path.write_bytes((body + ',\n' + lines + '\n}\n').encode('utf-8'))
    json.loads(path.read_bytes().decode('utf-8'))
    print(path.name, '加了', len(new), '个键')


def main():
    zh, en = entries(ZH, TALK_ZH), entries(EN, TALK_EN)
    assert set(zh) == set(en), set(zh) ^ set(en)
    add(LANG / 'zh_cn.json', zh)
    add(LANG / 'en_us.json', en)


if __name__ == '__main__':
    main()
